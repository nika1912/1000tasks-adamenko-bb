V = float(input("Введите V (скорость лодки): "))
U = float(input("Введите U (скорость течения): "))
T1 = float(input("Введите T1 (время по озеру): "))
T2 = float(input("Введите T2 (время по реке): "))

S1 = V * T1
S2 = (V - U) * T2
S = S1 + S2

print("Путь по озеру:", S1)
print("Путь по реке:", S2)
print("Общий путь:", S)
